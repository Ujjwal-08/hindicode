बराबर_हो(खाता.लेनदेन_संख्या, 3);
बराबर_हो(`${खाता}`, "राधा: ₹600");
त्रुटि_हो(() => खाता.जमा(10), सीमा_त्रुटि);
त्रुटि_हो(() => खाता.निकालो(1e6), /अपर्याप्त/);
